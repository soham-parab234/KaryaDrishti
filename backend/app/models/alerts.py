"""Early-Warning Alerts database models.

Conforms to LMIS Master R&D Section 11:
- Implements transparent rule-based alerts for Shortage Risk, Oversupply Risk,
  Emerging Demand, and Data Quality Warning.
- Records triggering rules, supporting evidence, severity, and review actions.
- Explicitly labels thresholds as configurable prototype defaults.
"""

from datetime import datetime, timezone
from sqlalchemy import String, Integer, Float, Text, DateTime, Index
from sqlalchemy.orm import Mapped, mapped_column

from backend.app.db.base import Base


class EarlyWarningAlert(Base):
    """Persisted early-warning alert generated by rule-based evaluation engine."""

    __tablename__ = "early_warning_alerts"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    alert_id: Mapped[str] = mapped_column(String(64), unique=True, index=True, nullable=False)
    nco_code: Mapped[str] = mapped_column(String(20), index=True, nullable=False)
    canonical_title: Mapped[str | None] = mapped_column(String(255), nullable=True)
    district_code: Mapped[str] = mapped_column(String(50), index=True, nullable=False)
    reporting_period: Mapped[str] = mapped_column(String(20), index=True, nullable=False)

    # Classification
    alert_type: Mapped[str] = mapped_column(
        String(50), nullable=False
    )  # SHORTAGE_RISK, OVERSUPPLY_RISK, EMERGING_DEMAND, DATA_QUALITY_WARNING
    severity: Mapped[str] = mapped_column(String(20), default="WARNING", nullable=False)  # CRITICAL, WARNING, INFO

    # Rule and Evidence
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    trigger_rule: Mapped[str] = mapped_column(Text, nullable=False)
    evidence_summary: Mapped[str] = mapped_column(Text, nullable=False)
    review_action_recommended: Mapped[str] = mapped_column(Text, nullable=False)

    # Triage and Planning Action Workflow
    triage_status: Mapped[str] = mapped_column(String(50), default="NEW", nullable=False)  # NEW, ACKNOWLEDGED, ESCALATED, RESOLVED
    triage_note: Mapped[str | None] = mapped_column(String(255), nullable=True)

    # Numerical metrics at time of alert
    observed_demand: Mapped[float | None] = mapped_column(Float, nullable=True)
    estimated_supply: Mapped[float | None] = mapped_column(Float, nullable=True)
    absolute_gap: Mapped[float | None] = mapped_column(Float, nullable=True)
    gap_rate_pct: Mapped[float | None] = mapped_column(Float, nullable=True)

    # Provenance and Disclaimers
    threshold_type: Mapped[str] = mapped_column(
        String(50), default="CONFIGURABLE_PROTOTYPE_DEFAULT", nullable=False
    )
    data_status: Mapped[str] = mapped_column(String(50), default="SYNTHETIC_DEMO", nullable=False)
    limitations: Mapped[str] = mapped_column(Text, nullable=False)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    __table_args__ = (
        Index("ix_alerts_lookup", "district_code", "alert_type", "severity"),
    )
